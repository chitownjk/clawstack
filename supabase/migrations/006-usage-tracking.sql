COMMENT ON COLUMN mc_tasks.cost_usd IS 'Estimated cost in USD for this task execution';

-- Function to get or create monthly usage record
CREATE OR REPLACE FUNCTION get_monthly_usage(account_uuid UUID, month_date DATE DEFAULT CURRENT_DATE)
RETURNS monthly_usage AS $$
DECLARE
  usage_record monthly_usage;
  account_limit INTEGER;
BEGIN
  -- Get account's plan limit
  SELECT 
    CASE plan_tier
      WHEN 'cloud' THEN 100      -- Solo
      WHEN 'cloud-developer' THEN 400
      WHEN 'cloud-plus' THEN 1000  -- Team
      ELSE NULL                    -- Free tiers = unlimited
    END INTO account_limit
  FROM accounts
  WHERE id = account_uuid;

  -- Get or create usage record for this month
  INSERT INTO monthly_usage (account_id, month, tasks_limit)
  VALUES (account_uuid, DATE_TRUNC('month', month_date), account_limit)
  ON CONFLICT (account_id, month) 
  DO UPDATE SET updated_at = NOW()
  RETURNING * INTO usage_record;

  RETURN usage_record;
END;
$$ LANGUAGE plpgsql;

-- Function to increment task count
CREATE OR REPLACE FUNCTION increment_task_usage(
  account_uuid UUID,
  tokens_input INTEGER DEFAULT 0,
  tokens_output INTEGER DEFAULT 0,
  cost DECIMAL DEFAULT 0
)
RETURNS VOID AS $$
BEGIN
  INSERT INTO monthly_usage (account_id, month, tasks_used, tokens_in, tokens_out, cost_usd, tasks_limit)
  VALUES (
    account_uuid,
    DATE_TRUNC('month', CURRENT_DATE),
    1,
    tokens_input,
    tokens_output,
    cost,
    (SELECT CASE plan_tier
      WHEN 'cloud' THEN 100
      WHEN 'cloud-developer' THEN 400
      WHEN 'cloud-plus' THEN 1000
      ELSE NULL
    END FROM accounts WHERE id = account_uuid)
  )
  ON CONFLICT (account_id, month)
  DO UPDATE SET
    tasks_used = monthly_usage.tasks_used + 1,
    tokens_in = monthly_usage.tokens_in + tokens_input,
    tokens_out = monthly_usage.tokens_out + tokens_output,
    cost_usd = monthly_usage.cost_usd + cost,
    updated_at = NOW();
END;
$$ LANGUAGE plpgsql;

-- Function to check if account is over limit
CREATE OR REPLACE FUNCTION is_over_limit(account_uuid UUID)
RETURNS BOOLEAN AS $$
DECLARE
  usage_record monthly_usage;
BEGIN
  usage_record := get_monthly_usage(account_uuid);
  
  -- NULL limit = unlimited (free tiers)
  IF usage_record.tasks_limit IS NULL THEN
    RETURN FALSE;
  END IF;
  
  RETURN usage_record.tasks_used >= usage_record.tasks_limit;
END;
$$ LANGUAGE plpgsql;

