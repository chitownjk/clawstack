-- Monthly usage tracking
CREATE TABLE IF NOT EXISTS monthly_usage (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  account_id UUID REFERENCES accounts(id) ON DELETE CASCADE,
  month DATE NOT NULL, -- First day of month (e.g., '2026-02-01')
  tasks_used INTEGER DEFAULT 0,
  tasks_limit INTEGER NOT NULL, -- Pulled from plan tier
  tokens_in INTEGER DEFAULT 0,
  tokens_out INTEGER DEFAULT 0,
  cost_usd DECIMAL(10,6) DEFAULT 0,
  created_at TIMESTAMP DEFAULT NOW(),
  updated_at TIMESTAMP DEFAULT NOW(),
  UNIQUE(account_id, month)
);

-- Add task-level tracking
ALTER TABLE mc_tasks 
  ADD COLUMN IF NOT EXISTS tokens_in INTEGER DEFAULT 0,
  ADD COLUMN IF NOT EXISTS tokens_out INTEGER DEFAULT 0,
  ADD COLUMN IF NOT EXISTS model_used TEXT,
  ADD COLUMN IF NOT EXISTS cost_usd DECIMAL(10,6) DEFAULT 0;

-- Indexes
CREATE INDEX IF NOT EXISTS idx_monthly_usage_account ON monthly_usage(account_id, month DESC);
CREATE INDEX IF NOT EXISTS idx_tasks_model ON mc_tasks(model_used);
CREATE INDEX IF NOT EXISTS idx_tasks_created_month ON mc_tasks(account_id, DATE_TRUNC('month', created_at));

-- Comments
COMMENT ON TABLE monthly_usage IS 'Track monthly task usage per account for billing limits';
COMMENT ON COLUMN monthly_usage.tasks_limit IS 'Max tasks for current plan (100, 400, 1000, or NULL for unlimited)';
COMMENT ON COLUMN mc_tasks.tokens_in IS 'Input tokens consumed by this task';
COMMENT ON COLUMN mc_tasks.tokens_out IS 'Output tokens generated by this task';
